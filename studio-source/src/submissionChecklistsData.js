export const allChecklistRecords=[...submissionDeadlines.map(item=>({...item,kind:'deadline'})),...programmeRequirements.map(item=>({...item,kind:'requirement'})),...subjectRequirements.map(item=>({...item,kind:'subject'})),...unresolvedChecks.map(item=>({...item,kind:'unresolved'}))];
export function formatChecklistDate(value,monthOnly=false){return new Intl.DateTimeFormat('en-US',{year:'numeric',month:'long',...(monthOnly?{}:{day:'numeric'}),timeZone:'UTC'}).format(new Date(value+(monthOnly?'-01':'')+'T12:00:00Z'));}
export function checklistItems(item){return (item.checks||item.deliverables||[]).map((text,index)=>({key:'submission:'+item.id+':review:'+index,text}));}
export function filterChecklistRecords({view='dates',programme='All',month='All',query='',selected=''}={}){const words=query.trim().toLowerCase().split(/\s+/).filter(Boolean);return allChecklistRecords.filter(item=>(view==='dates'?item.kind==='deadline':item.kind!=='deadline')&&(programme==='All'||item.programme.includes(programme))&&(view!=='dates'||month==='All'||item.date.slice(0,7)===month)&&(view!=='dates'||!selected||item.id===selected)&&words.every(word=>JSON.stringify(item).toLowerCase().includes(word)));}
export function clearChecklistTicks(notes,items){const next={...notes};items.flatMap(checklistItems).forEach(item=>delete next[item.key]);return next;}
export function checklistSummary(items,notes={},context=''){const lines=['AVHS IB | PUBLIC-SOURCE SUBMISSION CHECKLIST','Original planning reference, not an official form, complete session calendar or school policy.','Only the linked public sources support the dates and requirements included here.','Source review: '+checklistVersion+'. '+context,'Ticks mean reviewed only, not registration, completion or submission proof.','This local text copy is not submitted to the school. Unticked does not mean overdue.','Do not include names, student records, marks or confidential evidence.','School/coordinator deadlines are not student hand-in dates. Confirm applicability, current procedures, cutoff times and school arrangements.',''];for(const item of items){lines.push(item.programme+' | '+(item.date?formatChecklistDate(item.date):'Requirement / confirmation')+' | '+(item.title||item.subject),'Role: '+item.role);for(const key of ['condition','text','detail','scope','dateProvenance','cutoff'])if(item[key])lines.push(item[key]);for(const tick of checklistItems(item))lines.push((notes[tick.key]===true?'[x] ':'[ ] ')+tick.text);for(const id of item.sourceIds||[]){const source=checklistSources[id];if(source)lines.push('Source: '+source.title+'\n'+source.url);}lines.push('');}lines.push('COVERAGE: This is not the full session calendar. Obtain other dates and local expectations from the coordinator.');return lines.join('\n');}
